import type { Point, ShapeInput, StyleShape } from '../../src/index'

/** Logical size of the measured canvas */
export const CANVAS_WIDTH = 1000
export const CANVAS_HEIGHT = 600

/** The shapes fill this area: the band below it stays empty, to start a selection frame */
export const SHAPES_AREA = { width: 1000, height: 500 }

const STYLE = { fillColor: '#4a90d9', strokeColor: '#000000', lineWidth: 1, opacity: 100, lineDash: 0, closedPoints: 0 }

type Cell = { x: number; y: number; width: number; height: number }

/** Cells of a grid filling the shapes area, one per shape, with a margin */
const getGridCells = (count: number): Cell[] => {
  const columns = Math.ceil(Math.sqrt((count * SHAPES_AREA.width) / SHAPES_AREA.height))
  const rows = Math.ceil(count / columns)
  const cellWidth = SHAPES_AREA.width / columns
  const cellHeight = SHAPES_AREA.height / rows

  return Array.from({ length: count }, (_, index) => ({
    x: Math.round((index % columns) * cellWidth + cellWidth * 0.15),
    y: Math.round(Math.floor(index / columns) * cellHeight + cellHeight * 0.15),
    width: Math.round(cellWidth * 0.7),
    height: Math.round(cellHeight * 0.7)
  }))
}

const createRect = (cell: Cell, style: StyleShape = STYLE): ShapeInput => ({ type: 'rect', ...cell, rotation: 0, style })

/** Generates `count` rectangles laid out on a grid, always the same for a given count */
export const generateShapes = (count: number): ShapeInput[] => getGridCells(count).map(cell => createRect(cell))

/** The rectangles of the grid, filled and stroked at half opacity: each one is drawn with its opacity */
export const generateTransparentShapes = (count: number): ShapeInput[] => getGridCells(count).map(cell => createRect(cell, { ...STYLE, opacity: 50 }))

/** A shape of each type in turn, one out of two at half opacity */
const createMixedShape = ({ x, y, width, height }: Cell, index: number): ShapeInput => {
  const style = { ...STYLE, opacity: index % 2 === 0 ? 100 : 50 }
  const center: Point = [x + width / 2, y + height / 2]
  switch (index % 9) {
    case 0:
      return createRect({ x, y, width, height }, style)
    case 1:
      return { type: 'ellipse', x: center[0], y: center[1], radiusX: width / 2, radiusY: height / 2, style }
    case 2:
      return { type: 'circle', x: center[0], y: center[1], radius: Math.min(width, height) / 2, style }
    case 3:
      return {
        type: 'line',
        points: [
          [x, y],
          [x + width, y + height]
        ],
        style: { ...style, lineWidth: 2, arrowStart: 'triangle', arrowEnd: 'triangle' }
      }
    case 4:
      return {
        type: 'polygon',
        points: [
          [x + width / 2, y],
          [x + width, y + height * 0.4],
          [x + width * 0.8, y + height],
          [x + width * 0.2, y + height],
          [x, y + height * 0.4]
        ],
        style: { ...style, closedPoints: 1 }
      }
    case 5:
      return {
        type: 'curve',
        points: [
          [x, y + height],
          [x + width / 3, y],
          [x + (width * 2) / 3, y + height],
          [x + width, y]
        ],
        style: { ...style, fillColor: 'transparent', lineWidth: 2 }
      }
    case 6:
      return {
        type: 'text',
        x,
        y,
        value: ['Text', 'on two lines'],
        fontSize: Math.max(4, height / 3),
        style: { strokeColor: '#000000', opacity: style.opacity }
      }
    case 7:
      return {
        type: 'brush',
        points: [Array.from({ length: 30 }, (_, step): Point => [x + (width * step) / 29, y + height / 2 + Math.sin(step / 2) * (height / 2)])],
        style: { ...style, lineWidth: 2 }
      }
    default:
      return { type: 'square', x, y, width: Math.min(width, height), height: Math.min(width, height), style }
  }
}

/** Generates `count` shapes of all the types, laid out on the grid */
export const generateMixedShapes = (count: number): ShapeInput[] => getGridCells(count).map(createMixedShape)

/** Id of the large shape which is not filled, generated by generateOutlinedShapes */
export const OUTLINE_ID = 'outline'

/**
 * The grid, under a large rectangle which is only stroked: a selection frame inside it never crosses its stroke,
 * so each point of the frame is checked against it
 */
export const generateOutlinedShapes = (count: number): ShapeInput[] => [
  {
    id: OUTLINE_ID,
    type: 'rect',
    x: 5,
    y: 5,
    width: CANVAS_WIDTH - 10,
    height: CANVAS_HEIGHT - 10,
    rotation: 0,
    style: { ...STYLE, fillColor: 'transparent', lineWidth: 2 }
  },
  ...generateShapes(count - 1)
]

/** Size of the photos of generatePictures, much larger than they are drawn */
const PHOTO_SIZE = { width: 3000, height: 2000 }

/** Place of the photos in the canvas */
const PICTURE_CELLS: Cell[] = [
  { x: 60, y: 40, width: 300, height: 200 },
  { x: 380, y: 160, width: 300, height: 200 },
  { x: 650, y: 280, width: 300, height: 200 }
]

let photo: Promise<Blob> | undefined

/** A photo-like JPEG, made once: gradients and noise, so that it is neither tiny nor trivial to decode */
const getPhoto = () => {
  photo ??= (() => {
    const canvas = new OffscreenCanvas(PHOTO_SIZE.width, PHOTO_SIZE.height)
    const ctx = canvas.getContext('2d')!
    const gradient = ctx.createLinearGradient(0, 0, PHOTO_SIZE.width, PHOTO_SIZE.height)
    gradient.addColorStop(0, '#1d4e89')
    gradient.addColorStop(0.5, '#f2a65a')
    gradient.addColorStop(1, '#2a9d8f')
    ctx.fillStyle = gradient
    ctx.fillRect(0, 0, PHOTO_SIZE.width, PHOTO_SIZE.height)
    // always the same noise: a fixed sequence instead of Math.random
    let seed = 1
    const random = () => {
      seed = (seed * 16807) % 2147483647
      return seed / 2147483647
    }
    for (let index = 0; index < 4000; index++) {
      ctx.fillStyle = `hsla(${random() * 360}, 60%, 50%, 0.4)`
      ctx.beginPath()
      ctx.arc(random() * PHOTO_SIZE.width, random() * PHOTO_SIZE.height, 5 + random() * 60, 0, Math.PI * 2)
      ctx.fill()
    }
    return canvas.convertToBlob({ type: 'image/jpeg', quality: 0.9 })
  })()
  return photo
}

/**
 * The grid of rectangles under 3 large photos, in the foreground. Their sources are blob URLs, as a consumer may give
 * them: a URL is revoked once its picture is loaded, so each call gives new ones
 */
export const generatePictures = async (count: number): Promise<ShapeInput[]> => {
  const blob = await getPhoto()
  const pictures = PICTURE_CELLS.map((cell): ShapeInput => ({ type: 'picture', ...cell, rotation: 0, src: URL.createObjectURL(blob) }))
  return [...pictures, ...generateShapes(count - pictures.length)]
}

/** The photo of generatePictures, as a file chosen by the user */
export const getPhotoFile = async () => new File([await getPhoto()], 'photo.jpg', { type: 'image/jpeg' })

/** Strokes of a long brush: drawn by the long-brush scenario, and given by generateLongBrush */
export const LONG_BRUSH_STROKES = 4
const LONG_BRUSH_POINTS = 1000

/**
 * The grid, under a brush of 4 strokes of 1000 points in the foreground: several minutes of drawing in the same shape,
 * when the brush is not done on release. The points are rounded, like the ones of the cursor
 */
export const generateLongBrush = (count: number): ShapeInput[] => [
  {
    type: 'brush',
    points: Array.from({ length: LONG_BRUSH_STROKES }, (_, stroke) =>
      Array.from(
        { length: LONG_BRUSH_POINTS },
        (_, step): Point => [Math.round(50 + (900 * step) / (LONG_BRUSH_POINTS - 1)), Math.round(100 + stroke * 120 + Math.sin(step / 10) * 20)]
      )
    ),
    style: { ...STYLE, lineWidth: 2 }
  },
  ...generateShapes(count - 1)
]

/** Center of a rectangle, in canvas coordinates */
export const getShapeCenter = (shape: ShapeInput): Point => {
  if (shape.type !== 'rect' && shape.type !== 'picture') throw new Error('Only the center of a rectangle or a picture is known')
  return [shape.x + shape.width / 2, shape.y + shape.height / 2]
}

/** A point where the shape can be grabbed: the center of a rectangle or a picture, the middle point of the first stroke of a brush */
export const getGrabPoint = (shape: ShapeInput): Point => {
  if (shape.type !== 'brush') return getShapeCenter(shape)
  const stroke = shape.points[0]!
  return stroke[Math.floor(stroke.length / 2)]!
}
